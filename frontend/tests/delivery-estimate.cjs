const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const path = require('node:path');
const scope = { exports: {}, Intl, Date };
vm.createContext(scope);
vm.runInContext(ts.transpileModule(fs.readFileSync(path.join(__dirname, '../src/lib/deliveryEstimate.ts'), 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText, scope);
const estimate = scope.exports.estimateDelivery;
assert.equal(estimate(new Date('2026-10-24T15:00:00Z'), true).deliveryDate, '2026-10-29');
assert.equal(estimate(new Date('2026-10-26T15:00:00Z'), true).readyDate, '2026-10-30');
assert.equal(estimate(new Date('2026-10-26T15:00:00Z'), true).deliveryDate, '2026-11-03');
assert.equal(estimate(new Date('2026-10-27T19:59:00Z'), false).deliveryDate, '2026-10-27');
assert.equal(estimate(new Date('2026-10-27T20:00:00Z'), false).deliveryDate, '2026-10-29');
assert.equal(estimate(new Date('2026-10-28T00:30:00Z'), false).deliveryDate, '2026-10-29');
assert.equal(estimate(new Date('2026-10-29T21:00:00Z'), false).deliveryDate, '2026-11-03');
assert.equal(estimate(new Date('2024-02-23T15:00:00Z'), true).readyDate, '2024-02-29');
assert.throws(() => estimate(new Date('invalid')), /Fecha/);
assert.match(estimate(new Date('2026-10-24T15:00:00Z'), true).deliveryLabel, /jueves.*29.*octubre/);
console.log('Delivery estimate regression checks passed: weekends, 17h cutoff, Argentina timezone, month/leap boundary and invalid input.');
